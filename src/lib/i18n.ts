export type Lang = 'tr' | 'en';

/** Adres /en/ ile başlıyorsa İngilizce, aksi halde Türkçe. */
export const langOf = (url: URL | string): Lang => {
  const p = typeof url === 'string' ? url : url.pathname;
  return p === '/en' || p.startsWith('/en/') ? 'en' : 'tr';
};

